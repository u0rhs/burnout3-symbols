"""Write a README.md index into data folders that the documentation links to, so the links also work on
the GitHub Pages site (which has no folder listings).

    python3 tools/folder_index.py            (from the repository root; run by tools/rebuild.sh)
"""
import os
import urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

FOLDERS = {
    'data/burnout3-prototype': ('Burnout 3 prototype',
        'Exports from the Burnout 3 prototype disc (8 June 2004): the four link maps and assert files as text '
        '(`maps/`), modules with symbols (`modules/`), the disc listing, strings, executable headers and value '
        'database (`disc/`), and the original text link map (`originals/`). Described in [data](../README.md).'),
    'data/burnout3-retail': ('Burnout 3 retail (SLUS-21050)',
        'Exports from the NTSC-U retail disc: the disc listing, strings, executable headers and value database '
        '(`disc/`), the memory map, vehicle IDs and event medals from cheat codes and patches, and third-party '
        'PCSX2 patches. Described in [data](../README.md) and the '
        '[retail memory map](../../docs/reference/retail-memory-map.md).'),
    'data/burnout2-prototype': ('Burnout 2 prototype (29 July 2002)',
        'Exports from the Burnout 2 prototype: the executable\'s symbols and DWARF 1 debug information '
        '(`SLUS_204.97/`), modules with symbols (`modules/`), the disc listing and strings (`disc/`), and the '
        'original IOP link maps (`originals/`). Described in [data](../README.md).'),
    'data/burnout-revenge-prototype': ('Burnout Revenge prototype (14 July 2005)',
        'Exports from the Burnout Revenge July 14, 2005 PS2 prototype (`SLUS_212.42`), which kept its symbol table and '
        'GCC debug information: types with members and methods, functions with parameter names, globals and source '
        'files (`SLUS_212.42/`). Revenge was built on Burnout 3\'s code. Written by `tools/export_revenge.py`; the '
        'executable and its link map are not copied. Described on [builds](../../docs/builds.md#burnout-revenge-prototypes-2005-to-2006).'),
    'data/burnout3-review-us-2004-07-20': ('Burnout 3 US review build (20 July 2004, 11:11)',
        'Exports from the US review disc ("Print Reviews Only Alpha 1 07-18-2004"): the disc listing, strings and headers '
        'of the stripped `SLUS_210.50`, and the value database (`disc/`). Described on [builds](../../docs/builds.md).'),
    'data/burnout3-review-pal-2004-07-20': ('Burnout 3 PAL review build (20 July 2004, 11:14)',
        'Exports from the PAL review disc ("Reviewable 105263 PAL1EXT"): the disc listing, strings and headers of the '
        'stripped `SLES_525.84`, and the value database (`disc/`). Described on [builds](../../docs/builds.md).'),
    'data/burnout3-prototype/originals': ('Burnout 3 prototype: original files',
        'The prototype executable\'s text link map, unchanged. Its export is in `../maps/`.'),
    'data/burnout2-prototype/originals': ('Burnout 2 prototype: original files',
        'Text link maps of three IOP modules, unchanged.'),
    'data/burnout3-retail/disc/strings': ('Burnout 3 retail: strings',
        'Printable strings of `SLUS_210.50` with their addresses, all together and sorted by kind.'),
    'data/burnout2-prototype/SLUS_204.97/source_outline': ('Burnout 2 source outlines',
        'One file per Burnout 2 source file, at Criterion\'s paths: every function\'s signature, parameters, '
        'locals and scopes, with addresses and line ranges, rebuilt from the debug information. No code '
        'survives. `renderware_and_libraries/` holds files compiled without a path.'),
    'data/burnout2-prototype/SLUS_204.97/source_outline/gamesource/Render': ('Burnout 2 renderer outlines',
        'The Burnout 2 rendering code: the PS2 pipelines (`PS2PrelitWorld2`, `PS2InstancedPrelit2`, '
        '`PS2InstancedLit2`, `PS2CarRenderer`, `PS2ParametricParticle`) and the effects (coronas, particles, '
        'rain, snow, sparks, sun), the ancestors of Burnout 3\'s renderer.'),
    'docs/reference/data': ('Reference tables (CSV)',
        'The larger reference tables as CSV, generated with the [reference pages](../README.md).'),
}


def link(rel):
    return urllib.parse.quote(rel.replace(os.sep, '/'))


def main():
    for folder, (title, about) in FOLDERS.items():
        d = os.path.join(ROOT, folder)
        if not os.path.isdir(d):
            continue
        lines = ['# %s' % title, '', '> Folder index generated by `tools/folder_index.py`.', '', about, '']
        subdirs, files = [], []
        for name in sorted(os.listdir(d), key=str.lower):
            if name.startswith('.') or name == 'README.md':
                continue
            (subdirs if os.path.isdir(os.path.join(d, name)) else files).append(name)
        deep = folder.endswith('source_outline') or folder.endswith('/Render')
        if subdirs:
            lines += ['## Folders', '']
            for s in subdirs:
                if os.path.exists(os.path.join(d, s, 'README.md')):
                    lines.append('- [%s/](%s/README.md)' % (s, link(s)))
                elif deep:
                    lines.append('- **%s/**' % s)
                    for dp, dn, fn in os.walk(os.path.join(d, s)):
                        dn.sort(key=str.lower)
                        for f in sorted(fn, key=str.lower):
                            rel = os.path.relpath(os.path.join(dp, f), d)
                            lines.append('  - [%s](%s)' % (os.path.relpath(os.path.join(dp, f), os.path.join(d, s)), link(rel)))
                else:
                    lines.append('- `%s/`' % s)
            lines.append('')
        if files:
            lines += ['## Files', '']
            for f in files:
                size = os.path.getsize(os.path.join(d, f))
                lines.append('- [%s](%s) (%s bytes)' % (f, link(f), format(size, ',')))
            lines.append('')
        with open(os.path.join(d, 'README.md'), 'w') as fh:
            fh.write('\n'.join(lines))
    print('folder indexes written:', len(FOLDERS))


if __name__ == '__main__':
    main()
