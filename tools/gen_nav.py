"""Generate the navigation from one map of the documentation:

  - _includes/components/site_nav.html   the website's sidebar (grouped, collapsible; the theme's own
                                         script opens the group of the current page)
  - README.md                            the "Contents" section between the contents markers
  - docs/README.md                       the same map, as the docs folder's contents page

    python3 tools/gen_nav.py            (from the repository root; run by tools/rebuild.sh)

To add a page to the navigation, add it to NAV below. Pages listed by folder (systems, reference) are
picked up automatically.
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = 'https://github.com/u0rhs/burnout3-symbols'


def title_of(path):
    p = os.path.join(ROOT, path)
    for line in open(p):
        m = re.match(r'#\s+(.+)', line)
        if m:
            return re.sub(r'`', '', m.group(1)).strip()
    return os.path.basename(path)


def folder(pattern, skip=()):
    out = []
    for p in sorted(glob.glob(os.path.join(ROOT, pattern))):
        rel = os.path.relpath(p, ROOT).replace(os.sep, '/')
        if os.path.basename(rel) == 'README.md' or rel in skip:
            continue
        out.append((None, rel))
    return out


RETAIL = ['docs/reference/retail-function-names.md', 'docs/reference/retail-memory-map.md',
          'docs/reference/nahelam-mods.md', 'docs/discs.md']
B2_LINEAGE = ['docs/reference/class-ancestors.md', 'docs/reference/class-lineage.md',
              'docs/reference/function-lineage.md', 'docs/reference/source-file-lineage.md',
              'docs/reference/b2-classes.md', 'docs/reference/class-hierarchy.md', 'docs/reference/enums.md',
              'docs/reference/renderware-api.md']

# (title or None for the page's own title, path or URL, [children])
NAV = [
    ('Home', 'README.md', []),
    ('Symbols and maps', 'docs/files.md', []),
    ('Getting started', 'docs/README.md', [
        (None, 'docs/builds.md'),
        (None, 'docs/data-guide.md'),
        (None, 'docs/glossary.md'),
    ]),
    ('Game systems', 'docs/systems/README.md', folder('docs/systems/*.md')),
    ('Classes', 'docs/classes/README.md', []),
    ('Renderer overview', 'docs/renderer-overview.md', []),
    ('Retail game', 'docs/reference/retail-function-names.md', [(None, p) for p in RETAIL]),
    ('Reference: Burnout 3', 'docs/reference/README.md',
     folder('docs/reference/*.md', skip=set(RETAIL + B2_LINEAGE))),
    ('Reference: Burnout 2 lineage', 'docs/reference/class-ancestors.md', [(None, p) for p in B2_LINEAGE]),
    ('Uses', 'docs/avenues/README.md', folder('docs/avenues/*.md')),
    ('Formats', 'docs/formats/README.md', folder('docs/formats/*.md')),
    ('Data and tools', 'data/README.md', [
        ('Burnout 3 prototype data', 'data/burnout3-prototype/README.md'),
        ('Burnout 3 retail data', 'data/burnout3-retail/README.md'),
        ('Burnout 3 US review build data', 'data/burnout3-review-us-2004-07-20/README.md'),
        ('Burnout 3 PAL review build data', 'data/burnout3-review-pal-2004-07-20/README.md'),
        ('Burnout 2 prototype data', 'data/burnout2-prototype/README.md'),
        ('Burnout 2 source outlines', 'data/burnout2-prototype/SLUS_204.97/source_outline/README.md'),
        ('Reference tables (CSV)', 'docs/reference/data/README.md'),
        (None, 'docs/tools.md'),
    ]),
    ('Project', 'docs/related-projects.md', [
        (None, 'docs/related-projects.md'),
        (None, 'docs/open-questions.md'),
        (None, 'docs/changelog.md'),
        ('GitHub repository', REPO),
    ]),
]


def site_url(path):
    if path.startswith('http'):
        return path
    if path == 'README.md':
        return '/'
    if path.endswith('/README.md'):
        return '/' + path[:-len('README.md')]
    return '/' + path[:-3] + '.html'


def rel_link(path, frm_dir):
    if path.startswith('http'):
        return path
    return os.path.relpath(os.path.join(ROOT, path), os.path.join(ROOT, frm_dir)).replace(os.sep, '/')


def label(t, p):
    return t or title_of(p)


def write_sidebar():
    H = ['{%- comment -%}', '  Generated by tools/gen_nav.py from its NAV map. Do not edit by hand.', '{%- endcomment -%}',
         '<nav aria-label="Main" id="site-nav" class="site-nav">', '<ul class="nav-list">']
    for t, p, kids in NAV:
        href = p if p.startswith('http') else "{{ '%s' | relative_url }}" % site_url(p)
        H.append('<li class="nav-list-item">')
        if kids:
            H.append('<button class="nav-list-expander btn-reset" aria-label="toggle items in %s category" '
                     'aria-pressed="false"><svg viewBox="0 0 24 24" aria-hidden="true"><use xlink:href="#svg-arrow-right">'
                     '</use></svg></button>' % label(t, p))
        H.append('<a href="%s" class="nav-list-link">%s</a>' % (href, label(t, p)))
        if kids:
            H.append('<ul class="nav-list">')
            for kt, kp in kids:
                if kp.startswith('http'):
                    H.append('<li class="nav-list-item"><a href="%s" class="nav-list-link" target="_blank" rel="noopener">%s '
                             '<svg viewBox="0 0 24 24" aria-hidden="true"><use xlink:href="#svg-external-link"></use></svg></a></li>'
                             % (kp, label(kt, kp)))
                else:
                    H.append('<li class="nav-list-item"><a href="{{ \'%s\' | relative_url }}" class="nav-list-link">%s</a></li>'
                             % (site_url(kp), label(kt, kp)))
            H.append('</ul>')
        H.append('</li>')
    H += ['</ul>', '</nav>', '']
    os.makedirs(os.path.join(ROOT, '_includes', 'components'), exist_ok=True)
    with open(os.path.join(ROOT, '_includes', 'components', 'site_nav.html'), 'w') as fh:
        fh.write('\n'.join(H))


def contents_md(frm_dir):
    L = []
    for t, p, kids in NAV:
        if p == 'README.md':
            continue
        if not kids:
            L.append('- **[%s](%s)**' % (label(t, p), rel_link(p, frm_dir)))
            continue
        L.append('- **[%s](%s)**' % (label(t, p), rel_link(p, frm_dir)))
        L.append('  ' + ' · '.join('[%s](%s)' % (label(kt, kp), rel_link(kp, frm_dir)) for kt, kp in kids))
    return '\n'.join(L)


def write_readme():
    p = os.path.join(ROOT, 'README.md')
    s = open(p).read()
    start, end = '<!-- contents:start -->', '<!-- contents:end -->'
    block = start + '\n' + contents_md('') + '\n' + end
    if start in s:
        s = re.sub(re.escape(start) + r'.*?' + re.escape(end), lambda m: block, s, flags=re.S)
    else:
        raise SystemExit('README.md has no contents markers')
    open(p, 'w').write(s)


def write_docs_readme():
    p = os.path.join(ROOT, 'docs', 'README.md')
    with open(p, 'w') as fh:
        fh.write('# Documentation\n\n> Generated by `tools/gen_nav.py`; the same map as the website\'s sidebar and the '
                 '[home page](../README.md).\n\nEvery page of the documentation, by section.\n\n' + contents_md('docs') + '\n')


def check():
    missing = []
    for t, p, kids in NAV:
        for path in [p] + [kp for _, kp in kids]:
            if not path.startswith('http') and not os.path.exists(os.path.join(ROOT, path)):
                missing.append(path)
    listed = set(p for _, p, _ in NAV) | set(kp for _, _, kids in NAV for _, kp in kids)
    pages = set(os.path.relpath(f, ROOT).replace(os.sep, '/') for f in glob.glob(os.path.join(ROOT, 'docs', '**', '*.md'), recursive=True))
    pages -= set(p for p in pages if p.startswith('docs/classes/') and not p.endswith('README.md'))
    unlisted = sorted(pages - listed)
    return missing, unlisted


def main():
    missing, unlisted = check()
    if missing:
        raise SystemExit('NAV lists missing pages: %s' % missing)
    write_sidebar()
    write_readme()
    write_docs_readme()
    print('navigation written; docs pages not in the sidebar:', unlisted or 'none')


if __name__ == '__main__':
    main()
